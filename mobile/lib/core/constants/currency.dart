/// Курс лев/евро за задължителното двойно обозначаване на цените.
///
/// Съгласно Закона за въвеждане на еврото в Република България, цените
/// се изписват едновременно в евро и левове, като левовата равностойност
/// се изчислява по фиксирания курс на БНБ/Валутния борд:
///
///   1 EUR = 1,95583 BGN
///
/// Това е фиксиран, законово определен курс (не пазарен/плаващ), затова е
/// константа тук, а не стойност, теглена от външен източник.
library;

class Currency {
  Currency._();

  /// Фиксиран курс лев/евро.
  static const double bgnPerEur = 1.95583;

  /// Левова равностойност на сума в евро.
  static double eurToBgn(double eurAmount) => eurAmount * bgnPerEur;

  /// Форматирана левова равностойност, напр. "6.46 лв.".
  static String formattedBgn(double eurAmount) {
    return '${eurToBgn(eurAmount).toStringAsFixed(2)} лв.';
  }
}
